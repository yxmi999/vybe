// Generates src/app/theme-light.css — the light theme.
//
// The app is styled dark-first with Tailwind utilities (text-white/45,
// bg-white/[0.04], zinc-400, violet-300 …). Tailwind v4 renders every one of
// those through a CSS variable, so instead of touching every component the
// light theme redefines the variables under `html.light`:
//   • white ⇄ near-black (so "white at 45%" text becomes "ink at 45%")
//   • every colour scale reversed (50⇄950, 100⇄900 … 500 stays), so a light
//     tint used as text on dark becomes the matching dark shade on light
//   • the dark surface tokens (--d08 … --d1d) become light surfaces
// `.keep-dark` restores the dark values inside it (video stages, landing).
//
// Run: node scripts/gen-light-theme.mjs   (re-run after changing palettes)
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const twTheme = readFileSync(path.join(root, "node_modules/tailwindcss/theme.css"), "utf8");
const globals = readFileSync(path.join(root, "src/app/globals.css"), "utf8");

const PALETTES = ["red", "orange", "amber", "yellow", "lime", "green", "emerald", "teal", "cyan", "sky", "blue",
  "indigo", "violet", "purple", "fuchsia", "pink", "rose", "slate", "gray", "zinc", "neutral", "stone"];
const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

// Project overrides (globals.css @theme) win over Tailwind's defaults.
const values = {};
for (const src of [twTheme, globals]) {
  for (const m of src.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) values[`${m[1]}-${m[2]}`] = m[3].trim();
}

// Dark surfaces (hex in the old classes) → light surfaces. In dark, lighter
// = more elevated; in light, elevated surfaces are white over a grey page.
export const SURFACES = {
  d08: ["#080808", "#eeeef1"],
  d0a: ["#0a0a0a", "#f3f3f5"],
  d0b: ["#0b0b0b", "#f5f5f7"],
  d0c: ["#0c0c0c", "#fafafb"],
  d0e: ["#0e0e0e", "#fbfbfc"],
  d0f: ["#0f0f0f", "#fcfcfd"],
  d11: ["#111111", "#ffffff"],
  d12: ["#121212", "#ffffff"],
  d14: ["#141414", "#ffffff"],
  d16: ["#161616", "#f2f2f5"],
  d1a: ["#1a1a1a", "#ececf0"],
  d1c: ["#1c1c1c", "#e7e7ec"],
  d1d: ["#1d1d1d", "#e2e2e8"],
};

const lines = (pick) => {
  const out = [];
  for (const p of PALETTES) for (const s of STEPS) {
    const v = pick(p, s);
    if (v) out.push(`  --color-${p}-${s}: ${v};`);
  }
  return out;
};
const mirror = (s) => STEPS[STEPS.length - 1 - STEPS.indexOf(s)];

const css = `/* GENERATED by scripts/gen-light-theme.mjs — do not edit by hand. */

html.light {
  color-scheme: light;
  --background: #f3f3f5;
  --foreground: #16161b;
  --color-white: #121218;
  --color-black: #ffffff;
${Object.entries(SURFACES).map(([k, [, l]]) => `  --${k}: ${l};`).join("\n")}
${lines((p, s) => values[`${p}-${mirror(s)}`]).join("\n")}
}

/* Restore the dark theme inside .keep-dark (video stages, marketing pages). */
html.light .keep-dark {
  color-scheme: dark;
  color: var(--foreground);
  --background: #0a0a0a;
  --foreground: #ededed;
  --color-white: #ffffff;
  --color-black: #000000;
${Object.entries(SURFACES).map(([k, [d]]) => `  --${k}: ${d};`).join("\n")}
${lines((p, s) => values[`${p}-${s}`]).join("\n")}
}
`;
writeFileSync(path.join(root, "src/app/theme-light.css"), css);
console.log(`wrote src/app/theme-light.css (${css.length} bytes)`);
